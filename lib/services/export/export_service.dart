import 'dart:io';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:excel/excel.dart';
import 'package:path_provider/path_provider.dart';
import 'package:intl/intl.dart';
import 'package:share_plus/share_plus.dart';
import 'package:logger/logger.dart';

import '../../../features/reports/presentation/blocs/reports_state.dart';

/// Generates PDF and Excel attendance reports from loaded report data.
class ExportService {
  final Logger _log = Logger();

  // ─── PDF Export ───────────────────────────────────────────────────────────

  Future<void> exportPdf(ReportsLoaded state) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        header: (context) => _pdfHeader(state),
        footer: (context) => _pdfFooter(context),
        build: (context) => [
          pw.SizedBox(height: 20),
          _pdfSummarySection(state),
          pw.SizedBox(height: 20),
          _pdfStudentTable(state),
          if (_getLowAttendanceStudents(state).isNotEmpty) ...[
            pw.SizedBox(height: 20),
            _pdfLowAttendanceSection(state),
          ],
        ],
      ),
    );

    final bytes = await pdf.save();
    final dir = await getTemporaryDirectory();
    final file = File(
      '${dir.path}/attendance_${DateFormat('yyyy_MM_dd').format(DateTime.now())}.pdf',
    );
    await file.writeAsBytes(bytes);

    await Share.shareXFiles(
      [XFile(file.path)],
      subject: 'Attendance Report',
    );

    _log.i('PDF exported: ${file.path}');
  }

  pw.Widget _pdfHeader(ReportsLoaded state) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              'ATTENDANCE REPORT',
              style: pw.TextStyle(
                fontSize: 18,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.blue800,
              ),
            ),
            pw.Text(
              DateFormat('dd MMM yyyy').format(DateTime.now()),
              style: const pw.TextStyle(fontSize: 10),
            ),
          ],
        ),
        pw.Divider(color: PdfColors.blue800),
      ],
    );
  }

  pw.Widget _pdfFooter(pw.Context context) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Text('Generated by Face Attendance App',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey)),
        pw.Text(
          'Page ${context.pageNumber} of ${context.pagesCount}',
          style: const pw.TextStyle(fontSize: 8),
        ),
      ],
    );
  }

  pw.Widget _pdfSummarySection(ReportsLoaded state) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(12),
      decoration: pw.BoxDecoration(
        color: PdfColors.blue50,
        borderRadius: pw.BorderRadius.circular(6),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
        children: [
          _pdfStat('Total Classes', state.totalClasses.toString()),
          _pdfStat(
            'Avg Attendance',
            '${state.averageAttendance.toStringAsFixed(1)}%',
          ),
          _pdfStat(
            'Low Attendance',
            _getLowAttendanceStudents(state).length.toString(),
          ),
          _pdfStat('Total Students', state.studentSummaries.length.toString()),
        ],
      ),
    );
  }

  pw.Widget _pdfStat(String label, String value) {
    return pw.Column(
      children: [
        pw.Text(value,
            style: pw.TextStyle(
                fontSize: 16, fontWeight: pw.FontWeight.bold)),
        pw.Text(label, style: const pw.TextStyle(fontSize: 8)),
      ],
    );
  }

  pw.Widget _pdfStudentTable(ReportsLoaded state) {
    return pw.TableHelper.fromTextArray(
      headers: ['Roll No.', 'Student Name', 'Present', 'Total', '%', 'Status'],
      headerStyle: pw.TextStyle(
        fontWeight: pw.FontWeight.bold,
        color: PdfColors.white,
      ),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.blue800),
      rowDecoration: pw.BoxDecoration(
        border: pw.Border(
          bottom: pw.BorderSide(color: PdfColors.grey300),
        ),
      ),
      data: state.studentSummaries.map((s) {
        final pct = (s['percentage'] as double).toStringAsFixed(1);
        final isLow = (s['percentage'] as double) < 75;
        return [
          s['rollNumber'] ?? '',
          s['name'] ?? '',
          s['present'].toString(),
          s['total'].toString(),
          '$pct%',
          isLow ? 'LOW ⚠️' : 'OK',
        ];
      }).toList(),
      columnWidths: {
        0: const pw.FixedColumnWidth(60),
        1: const pw.FlexColumnWidth(),
        2: const pw.FixedColumnWidth(50),
        3: const pw.FixedColumnWidth(50),
        4: const pw.FixedColumnWidth(50),
        5: const pw.FixedColumnWidth(60),
      },
    );
  }

  pw.Widget _pdfLowAttendanceSection(ReportsLoaded state) {
    final low = _getLowAttendanceStudents(state);
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          '⚠️ Low Attendance Alert (< 75%)',
          style: pw.TextStyle(
            fontSize: 13,
            fontWeight: pw.FontWeight.bold,
            color: PdfColors.red,
          ),
        ),
        pw.SizedBox(height: 8),
        ...low.map((s) => pw.Text(
              '• ${s['rollNumber']} - ${s['name']}: '
              '${(s['percentage'] as double).toStringAsFixed(1)}%',
              style: const pw.TextStyle(color: PdfColors.red, fontSize: 10),
            )),
      ],
    );
  }

  List<Map<String, dynamic>> _getLowAttendanceStudents(ReportsLoaded state) {
    return state.studentSummaries
        .where((s) => (s['percentage'] as double) < 75)
        .toList();
  }

  // ─── Excel Export ─────────────────────────────────────────────────────────

  Future<void> exportExcel(ReportsLoaded state) async {
    final excel = Excel.createExcel();

    // Sheet 1: Summary
    final summarySheet = excel['Summary'];
    summarySheet.appendRow([
      TextCellValue('Attendance Report'),
      TextCellValue(DateFormat('dd MMM yyyy').format(DateTime.now())),
    ]);
    summarySheet.appendRow([]);
    summarySheet.appendRow([
      TextCellValue('Total Classes'),
      IntCellValue(state.totalClasses),
    ]);
    summarySheet.appendRow([
      TextCellValue('Average Attendance'),
      TextCellValue('${state.averageAttendance.toStringAsFixed(1)}%'),
    ]);
    summarySheet.appendRow([
      TextCellValue('Students Below 75%'),
      IntCellValue(_getLowAttendanceStudents(state).length),
    ]);

    // Sheet 2: Students
    final studentsSheet = excel['Student Attendance'];
    studentsSheet.appendRow([
      TextCellValue('Roll No.'),
      TextCellValue('Name'),
      TextCellValue('Classes Present'),
      TextCellValue('Total Classes'),
      TextCellValue('Percentage'),
      TextCellValue('Status'),
    ]);

    for (final s in state.studentSummaries) {
      final pct = (s['percentage'] as double);
      studentsSheet.appendRow([
        TextCellValue(s['rollNumber'] ?? ''),
        TextCellValue(s['name'] ?? ''),
        IntCellValue(s['present'] as int? ?? 0),
        IntCellValue(s['total'] as int? ?? 0),
        TextCellValue('${pct.toStringAsFixed(1)}%'),
        TextCellValue(pct < 75 ? 'LOW ATTENDANCE' : 'OK'),
      ]);
    }

    // Save and share
    final bytes = excel.save()!;
    final dir = await getTemporaryDirectory();
    final file = File(
      '${dir.path}/attendance_${DateFormat('yyyy_MM_dd').format(DateTime.now())}.xlsx',
    );
    await file.writeAsBytes(bytes);

    await Share.shareXFiles(
      [XFile(file.path)],
      subject: 'Attendance Report (Excel)',
    );

    _log.i('Excel exported: ${file.path}');
  }
}
